// @ts-nocheck (writes a file with node:fs; the app's tsconfig has no node types)
// Makes levelItemKindsData.ts from the level-check bank. Run it after you add, change or retire level-check questions:
//   UPDATE_LEVEL_KINDS=1 pnpm exec vitest run src/data/levelItemKindsGenerate.test.ts && pnpm exec prettier --write src/data/levelItemKindsData.ts
// Without UPDATE_LEVEL_KINDS this file does nothing (levelItemKinds.test.ts checks the result).
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, it } from 'vitest'
import { buildLevelBank } from './levelCheckBank'

describe.runIf(process.env.UPDATE_LEVEL_KINDS)('make levelItemKindsData.ts', () => {
  it('writes the file', () => {
    const groups = {}
    for (const item of buildLevelBank([])) {
      const kind = item.kind ?? 'type'
      const key = kind === 'choice' ? `choice:${item.choices?.length ?? 0}` : kind
      ;(groups[key] ??= []).push(item.id)
    }
    const data = Object.fromEntries(Object.entries(groups).map(([key, ids]) => [key, ids.join(' ')]))
    writeFileSync(
      join(process.cwd(), 'src/data/levelItemKindsData.ts'),
      `// GENERATED by src/data/levelItemKindsGenerate.test.ts from the level-check bank. Do not edit by hand.
export const levelItemKindsData: Record<string, string> = ${JSON.stringify(data, null, 2)}
`,
    )
  })
})
