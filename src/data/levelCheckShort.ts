import type { LevelItem } from './levelCheckBank'
import { pick } from './levelCheckDeep'

// Short tasks for the level check, in the style of the online placement tests of Oxford and Cambridge (written 15 Oct 2026):
// one short text or conversation, one question, three options; and one word to write in a gap. They are quick (about half a
// minute each) and ask for meaning, not for a translation. The formats are borrowed, the texts are the author's own.
//  - "What does B mean?": a short conversation where the answer is meant but not said (Oxford, Use of English part 2).
//  - "Which sentence means the same?": a notice, label, message or e-mail (Cambridge Linguaskill, reading).
//  - "Write ONE word": an open gap (Oxford part 3, Cambridge open gap-fill); only gaps with one possible word are used.
// Levels are the author's judgement, not calibrated on learners; when unsure, the level is the lower one.
type Level = 1 | 2 | 3 | 4

const meaning = (id: string, level: Level, lines: string[], question: string, answer: string, wrong: [string, string], explain: string) =>
  pick(`lcd-sm-${id}`, 'reading', level, question, answer, wrong, explain, {
    stimulus: lines.join('\n'),
    format: 'meaning',
    instruction: 'Read the conversation, then choose the best answer.',
  })

const notice = (id: string, level: Level, text: string, answer: string, wrong: [string, string], explain: string) =>
  pick(`lcd-nt-${id}`, 'reading', level, 'Which sentence means the same as the text?', answer, wrong, explain, {
    stimulus: text,
    format: 'notice',
    instruction: 'Read the text, then choose the sentence closest in meaning.',
  })

// answer: one word, or several accepted words separated by |
const openGap = (id: string, level: Level, prompt: string, answer: string, explain: string): LevelItem => ({
  id: `lcd-og-${id}`,
  skill: 'grammar',
  level,
  kind: 'type',
  prompt,
  answer,
  explain,
  log: false,
  instruction: 'Write ONE word in the gap.',
})

