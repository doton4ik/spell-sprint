// Finds "slips" that are really English words (turn → torn, cell, pot, peck) so Choose spelling and the
// Proofreading spelling hunt never offer them as mistakes. Uses the Tatoeba English sentences
// (research/tatoeba/eng_sentences.tsv, CC BY 2.0 FR, not in git) as a dictionary: a word seen in at
// least MIN sentences counts as real. Writes src/data/realWordTraps.ts.
//   node research/real-word-traps.mjs
import { createReadStream, mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { createInterface } from 'node:readline'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const MIN = 3

// 1. Dictionary: lower-case words and how many sentences use them.
const counts = new Map()
const lines = createInterface({ input: createReadStream(join(root, 'research/tatoeba/eng_sentences.tsv')) })
for await (const line of lines) {
  const text = line.split('\t')[2] ?? ''
  for (const word of new Set(text.toLocaleLowerCase().match(/[a-z]+(?:'[a-z]+)?/g) ?? [])) counts.set(word, (counts.get(word) ?? 0) + 1)
}
const isEnglish = (word) => (counts.get(word.toLocaleLowerCase()) ?? 0) >= MIN

// 2. The app's own slip makers (copied to a temp folder so Node can import the .ts files).
const dir = mkdtempSync(join(tmpdir(), 'traps-'))
for (const [file, name] of [['src/services/spellingDistractors.ts', 'spellingDistractors.ts'], ['src/services/proofreadingEngine.ts', 'proofreadingEngine.ts'], ['src/data/proofreadingTexts.ts', 'proofreadingTexts.ts']]) {
  writeFileSync(join(dir, name), readFileSync(join(root, file), 'utf8').replace("'../data/proofreadingTexts'", "'./proofreadingTexts.ts'").replace(/import \{ realWordExtras \} from '[^']+'\n/, 'const realWordExtras = ""\n'))
}
const { spellingDistractors } = await import(pathToFileURL(join(dir, 'spellingDistractors.ts')).href)
const engine = await import(pathToFileURL(join(dir, 'proofreadingEngine.ts')).href)
const { proofreadingTexts } = await import(pathToFileURL(join(dir, 'proofreadingTexts.ts')).href)

const csv = readFileSync(join(root, 'src/data/spell-sprint-built-in-library.csv'), 'utf8').split(/\r?\n/).slice(1)
const libraryWords = [...new Set(csv.map((line) => (line.match(/^[^,]*,("(?:[^"]|"")*"|[^,]*)/)?.[1] ?? '').replace(/^"|"$/g, '')).filter(Boolean))]

const traps = new Set()
// Library: every slip of every word (count 60 = all of them), word by word in a phrase.
for (const answer of libraryWords) {
  const parts = answer.toLocaleLowerCase().split(' ')
  for (const option of spellingDistractors(answer, () => false, 60)) {
    for (const piece of option.toLocaleLowerCase().split(' ')) if (!parts.includes(piece) && isEnglish(piece)) traps.add(piece)
  }
}
// Proofreading spelling hunt: many seeds per text, with no real-word filter.
for (const text of proofreadingTexts) {
  for (let seed = 1; seed <= 60; seed += 1) {
    const hunt = engine.buildSpellingHunt(text, seed, { known: new Set() })
    for (const slot of hunt.slots) if (isEnglish(slot.shown) && slot.shown.toLocaleLowerCase() !== slot.correct[0].toLocaleLowerCase()) traps.add(slot.shown.toLocaleLowerCase())
  }
}
const list = [...traps].sort()
const lines80 = []
let current = ''
for (const word of list) { if ((current + ' ' + word).length > 110) { lines80.push(current.trim()); current = '' } current += ' ' + word }
if (current.trim()) lines80.push(current.trim())
writeFileSync(join(root, 'src/data/realWordTraps.ts'), `// Real English words that the slip makers produce from library and text words (turn → torn, cell → cal → …).
// They must never be offered as "misspellings". Generated by research/real-word-traps.mjs from the
// Tatoeba sentence corpus (a word used in at least ${MIN} sentences counts as real). ${list.length} words.
export const realWordExtras = \`${lines80.join('\n')}\`
`)
console.log(`${counts.size} dictionary words; ${list.length} traps written to src/data/realWordTraps.ts`)
