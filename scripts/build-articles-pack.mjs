// Builds everything the article rules need from ONE source file, so the database and the app copy
// never drift apart:
//   database/rules-import/articles-pack.json  ->  database/content-pack-3-articles.sql   (run by the user in Supabase)
//                                              ->  src/data/builtInRules.json            (rules + examples, offline copy)
//                                              ->  src/data/builtInRuleExercises.json    (exercises by rule id, offline copy)
// Ids are derived from the slug, so running this again changes nothing. Usage: node scripts/build-articles-pack.mjs
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'

const pack = JSON.parse(readFileSync('database/rules-import/articles-pack.json', 'utf8'))

function uuid(key) {
  const hex = createHash('sha1').update(`spellsprint-articles:${key}`).digest('hex')
  const variant = ((parseInt(hex[16], 16) & 0x3) | 0x8).toString(16)
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-5${hex.slice(13, 16)}-${variant}${hex.slice(17, 20)}-${hex.slice(20, 32)}`
}
const q = (value) => (value === null || value === undefined ? 'null' : `'${String(value).replaceAll("'", "''")}'`)

const rules = []
const examples = []
const exercises = {}
for (const rule of pack.rules) {
  const id = uuid(rule.slug)
  rules.push({
    id,
    slug: rule.slug,
    title: rule.title,
    category: pack.category,
    rule_type: rule.rule_type,
    short_explanation: rule.short_explanation,
    tts_text: rule.tts_text ?? null,
    mnemonic: rule.mnemonic ?? null,
    source: 'built-in',
    visibility: 'public',
    is_active: true,
    metadata: {},
  })
  rule.examples.forEach((example, index) =>
    examples.push({
      id: uuid(`${rule.slug}|ex|${index}`),
      rule_id: id,
      example_type: example.type,
      text: example.text,
      correction: example.correction ?? null,
      note: example.note ?? null,
    }),
  )
  exercises[id] = rule.exercises.map((exercise, index) => ({
    id: uuid(`${rule.slug}|exr|${index}`),
    rule_id: id,
    exercise_type: 'multiple_choice',
    prompt: exercise.prompt,
    answer: exercise.answer,
    choices: exercise.choices,
    metadata: { set: 'articles-v1' },
  }))
}

// ---- the offline copies ----
const slugs = new Set(rules.map((rule) => rule.slug))
const builtIn = JSON.parse(readFileSync('src/data/builtInRules.json', 'utf8'))
const keptRules = builtIn.rules.filter((rule) => !slugs.has(rule.slug))
const droppedIds = new Set(builtIn.rules.filter((rule) => slugs.has(rule.slug)).map((rule) => rule.id))
builtIn.rules = [...keptRules, ...rules]
builtIn.examples = [...builtIn.examples.filter((example) => !droppedIds.has(example.rule_id)), ...examples]
writeFileSync('src/data/builtInRules.json', `${JSON.stringify(builtIn, null, 2)}\n`)
writeFileSync('src/data/builtInRuleExercises.json', `${JSON.stringify(exercises, null, 2)}\n`)

// ---- the SQL file ----
const ruleRows = rules
  .map(
    (r) =>
      `  (${q(r.id)}, ${q(r.slug)}, ${q(r.title)}, ${q(r.category)}, ${q(r.rule_type)}, ${q(r.short_explanation)}, ${q(r.tts_text)}, ${q(r.mnemonic)}, 'built-in', 'public', true)`,
  )
  .join(',\n')
const exampleRows = examples
  .map((e) => {
    const slug = rules.find((r) => r.id === e.rule_id).slug
    return `  (${q(e.id)}, ${q(slug)}, ${q(e.example_type)}, ${q(e.text)}, ${q(e.correction)}, ${q(e.note)})`
  })
  .join(',\n')
const exerciseRows = Object.values(exercises)
  .flat()
  .map((e) => {
    const slug = rules.find((r) => r.id === e.rule_id).slug
    return `  (${q(e.id)}, ${q(slug)}, ${q(e.exercise_type)}, ${q(e.prompt)}, ${q(e.answer)}, ${q(JSON.stringify(e.choices))}, ${q(JSON.stringify(e.metadata))})`
  })
  .join(',\n')

const sql = `-- Content pack 3: ARTICLES (a / an / the / no article). ${rules.length} rules, ${examples.length} examples, ${Object.values(exercises).flat().length} exercises.
-- GENERATED by scripts/build-articles-pack.mjs from database/rules-import/articles-pack.json. Do not edit by hand;
-- edit the JSON and run the script again.
--
-- What it does: adds the article rules to the Rules page (category english_grammar, shown as "English grammar"),
-- each with a short explanation, examples and multiple-choice exercises. Ids are fixed, so the offline copy
-- in the app (src/data/builtInRules.json) matches the database rows exactly.
-- Safe to run more than once: rules are unique on slug, examples and exercises are guarded against duplicates.
-- Run it in the Supabase SQL Editor (project "SpellSprint"). Needs rules-schema.sql to be applied already.
--
-- HOW TO UNDO (removes the rules; their examples and exercises go with them, learner progress on them too):
--   delete from public.rules where slug in (${rules.map((r) => q(r.slug)).join(', ')});

begin;

insert into public.rules (id, slug, title, category, rule_type, short_explanation, tts_text, mnemonic, source, visibility, is_active)
values
${ruleRows}
on conflict (slug) do nothing;

insert into public.rule_examples (id, rule_id, example_type, text, correction, note)
select v.id::uuid, r.id, v.example_type, v.text, v.correction, v.note
from (values
${exampleRows}
) as v(id, slug, example_type, text, correction, note)
join public.rules r on r.slug = v.slug
where not exists (select 1 from public.rule_examples e where e.rule_id = r.id and e.text = v.text);

insert into public.rule_exercises (id, rule_id, exercise_type, prompt, answer, choices, metadata)
select v.id::uuid, r.id, v.exercise_type, v.prompt, v.answer, v.choices::jsonb, v.metadata::jsonb
from (values
${exerciseRows}
) as v(id, slug, exercise_type, prompt, answer, choices, metadata)
join public.rules r on r.slug = v.slug
where not exists (select 1 from public.rule_exercises e where e.rule_id = r.id and e.prompt = v.prompt);

commit;
`
writeFileSync('database/content-pack-3-articles.sql', sql)
console.log(`${rules.length} rules, ${examples.length} examples, ${Object.values(exercises).flat().length} exercises written`)
