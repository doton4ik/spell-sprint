// Writes src/data/pairIndex.ts: the light list of pairs (id, words, level) and, for pairs of three or more words, the
// right answer of each sentence under a short key. The app's first screen needs only this; the 170 KB of sentences
// (src/data/pairDrills.ts) load with the Pairs page. Run after adding a pair:  node scripts/build-pair-index.mjs
// (pnpm check:pairs fails when the index is out of date).
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

const dir = mkdtempSync(join(tmpdir(), 'pairs-'))
writeFileSync(join(dir, 'pairs.ts'), readFileSync(new URL('../src/data/pairDrills.ts', import.meta.url), 'utf8'))
writeFileSync(join(dir, 'sentenceKey.ts'), readFileSync(new URL('../src/data/sentenceKey.ts', import.meta.url), 'utf8'))
const { pairDrills } = await import(pathToFileURL(join(dir, 'pairs.ts')).href)
const { sentenceKey } = await import(pathToFileURL(join(dir, 'sentenceKey.ts')).href)

const index = pairDrills.map((pair) => ({ id: pair.id, words: pair.words, level: pair.level }))
const answers = {}
for (const pair of pairDrills) {
  if (pair.words.length < 3) continue
  const byKey = {}
  for (const sentence of pair.sentences) {
    const key = sentenceKey(sentence.text)
    const position = pair.words.indexOf(sentence.answer)
    if (key in byKey && byKey[key] !== position) throw new Error(`${pair.id}: two sentences share the key ${key}`)
    byKey[key] = position
  }
  answers[pair.id] = byKey
}

const source = `// GENERATED by scripts/build-pair-index.mjs from pairDrills.ts. Do not edit by hand.
// The light list of look-alike pairs (the app's first screen reads this instead of the 170 KB of sentences in pairDrills.ts)
// and, for pairs of three or more words, the position of the right word in \`words\` for each sentence (key: sentenceKey()).
import type { PairLevel } from './pairDrills'

export type PairIndexEntry = { id: string; words: string[]; level: PairLevel }

export const pairIndex: PairIndexEntry[] = ${JSON.stringify(index)}

export const threeWordAnswers: Record<string, Record<string, number>> = ${JSON.stringify(answers)}
`
writeFileSync(new URL('../src/data/pairIndex.ts', import.meta.url), source)
console.log(`${index.length} pairs, ${Object.keys(answers).length} with three or more words, ${source.length} bytes`)
